CREATE TABLE sensors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    type VARCHAR(20) NOT NULL,
    number INTEGER NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    dry_adc INTEGER,
    wet_adc INTEGER,
    pulses_per_liter NUMERIC(12, 4),
    calibration_version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_sensors_type_number UNIQUE (type, number),
    CONSTRAINT ck_sensors_type CHECK (type IN ('UMIDADE', 'FLUXO')),
    CONSTRAINT ck_sensors_number CHECK (number > 0),
    CONSTRAINT ck_sensors_calibration CHECK (
        (type = 'UMIDADE' AND dry_adc IS NOT NULL AND wet_adc IS NOT NULL AND dry_adc <> wet_adc AND pulses_per_liter IS NULL)
        OR (type = 'FLUXO' AND pulses_per_liter IS NOT NULL AND pulses_per_liter > 0 AND dry_adc IS NULL AND wet_adc IS NULL)
    )
);

CREATE TABLE sensor_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id BIGINT NOT NULL REFERENCES sensors(id),
    message_id VARCHAR(128) NOT NULL,
    measured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    raw_value BIGINT NOT NULL,
    interval_ms BIGINT,
    converted_value NUMERIC(16, 4) NOT NULL,
    unit VARCHAR(12) NOT NULL,
    calibration_version INTEGER NOT NULL,
    CONSTRAINT uk_sensor_reading_message UNIQUE (sensor_id, message_id),
    CONSTRAINT ck_sensor_reading_raw CHECK (raw_value >= 0),
    CONSTRAINT ck_sensor_reading_interval CHECK (interval_ms IS NULL OR interval_ms > 0)
);

CREATE INDEX idx_sensor_readings_sensor_measured ON sensor_readings(sensor_id, measured_at DESC, id DESC);
