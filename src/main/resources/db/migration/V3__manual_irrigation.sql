CREATE TABLE manual_irrigations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id BIGINT NOT NULL REFERENCES sensors(id),
    owner_email VARCHAR(254) NOT NULL,
    device_username VARCHAR(64) NOT NULL,
    sensor_number INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    pulses_per_liter NUMERIC(12,4) NOT NULL CHECK (pulses_per_liter > 0),
    start_pulses BIGINT,
    last_pulses BIGINT,
    boot_id VARCHAR(128),
    liters NUMERIC(20,4) NOT NULL DEFAULT 0,
    interrupted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    stop_requested_at TIMESTAMP WITH TIME ZONE,
    measured_end_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    feedback_at TIMESTAMP WITH TIME ZONE,
    error VARCHAR(240),
    CONSTRAINT ck_manual_status CHECK (status IN ('STARTING','RUNNING','STOPPING','RESUMING','COMPLETED'))
);
CREATE UNIQUE INDEX uk_manual_active_device ON manual_irrigations(device_username) WHERE status <> 'COMPLETED';
CREATE INDEX idx_manual_owner_sensor ON manual_irrigations(owner_email, sensor_id, id DESC);
