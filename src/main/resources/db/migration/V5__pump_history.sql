CREATE TABLE pump_states (
    device VARCHAR(128) PRIMARY KEY,
    running BOOLEAN NOT NULL DEFAULT FALSE,
    measured_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE pump_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device VARCHAR(128) NOT NULL,
    running BOOLEAN NOT NULL,
    initial_state BOOLEAN NOT NULL,
    measured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_pump_event UNIQUE(device, measured_at)
);
CREATE INDEX idx_pump_events_device_time ON pump_events(device, measured_at DESC, id DESC);
